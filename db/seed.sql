-- Контрольная проверка наполнения
USE task_tracker;

SELECT 'users' AS table_name, COUNT(*) AS rows_count FROM users
UNION ALL SELECT 'projects',     COUNT(*) FROM projects
UNION ALL SELECT 'statuses',     COUNT(*) FROM statuses
UNION ALL SELECT 'tasks',        COUNT(*) FROM tasks
UNION ALL SELECT 'labels',       COUNT(*) FROM labels
UNION ALL SELECT 'task_labels',  COUNT(*) FROM task_labels
UNION ALL SELECT 'comments',     COUNT(*) FROM comments;

-- Задачи по статусам
SELECT s.name AS status, COUNT(*) AS tasks_count
FROM tasks t
JOIN statuses s ON s.id = t.status_id
GROUP BY s.id, s.name
ORDER BY tasks_count DESC;
